// __DIR__ — магическая константа, которая содержит путь к папке, где лежит текущий файл.
// Склеиваем путь: папка с сайтом + /data/counter.txt
$counter_file = __DIR__ . '/data/counter.txt';

// Если папки data не существует — создаём её.
// file_exists() проверяет существование файла или папки.
// is_dir() проверяет, является ли путь папкой.
if (!file_exists(__DIR__ . '/data')) {
    // mkdir() — создаёт папку.
    // Третий параметр true — создаёт рекурсивно (все вложенные папки, если их нет).
    // 0777 — права доступа (чтение/запись/исполнение для всех).
    mkdir(__DIR__ . '/data', 0777, true);
}

// Если файла счётчика не существует — создаём его с содержимым "0".
// file_put_contents() — записывает строку в файл (создаёт, если нет).
if (!file_exists($counter_file)) {
    file_put_contents($counter_file, '0');
}

// Открываем файл для чтения и записи (режим 'r+')
// fopen() возвращает указатель на файл (resource) — специальный объект для работы с файлом.
$fp = fopen($counter_file, 'r+');

/**
 * flock() — блокирует файл, чтобы при одновременных запросах не было гонки данных.
 * LOCK_EX — эксклюзивная блокировка (только один процесс может писать).
 * Это важно, чтобы при 100 одновременных заходах счётчик не сбился.
 */
if (flock($fp, LOCK_EX)) {
    // filesize() — размер файла в байтах. Если файл пустой, используем 1 (чтобы fread не ошиблась).
    $size = filesize($counter_file) ?: 1;

    // fread() — читает из файла $size байт.
    // (int) — преобразует прочитанную строку в целое число.
    $visitors = (int)fread($fp, $size);

    // Увеличиваем счётчик на 1.
    $visitors++;

    // ftruncate() — обрезает файл до нулевой длины (очищаем перед записью).
    ftruncate($fp, 0);

    // rewind() — перемещаем указатель в начало файла.
    rewind($fp);

    // fwrite() — записываем новое значение в файл.
    // (string) — преобразуем число в строку.
    fwrite($fp, (string)$visitors);

    // fflush() — принудительно сбрасываем буфер на диск (гарантия, что данные записались).
    fflush($fp);

    // Снимаем блокировку с файла.
    flock($fp, LOCK_UN);
}

// Закрываем файл (освобождаем ресурс).  Всегда закрывай файлы после работы!
fclose($fp);

// Форматируем число посетителей: 1234567 → "1 234 567"
$visitors_formatted = number_format($visitors, 0, '.', ' ');

