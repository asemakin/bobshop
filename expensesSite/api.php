/**
 * Функция форматирования бюджета региона: из миллиардов делает "1.2 трлн" или "890 млрд".
 *
 * @param float $billion Бюджет в миллиардах рублей
 * @return string Отформатированная строка
 */
function formatBudget($billion) {
    // Если бюджет больше или равен 1000 миллиардов (то есть 1 триллион)...
    if ($billion >= 1000) {
        // ... делим на 1000 и показываем в триллионах с одним знаком после запятой.
