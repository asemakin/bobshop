// -----------------------------------------------------------------------------
// 1. НАСТРОЙКИ СЧЁТЧИКА РАСХОДОВ НА СВО
// -----------------------------------------------------------------------------

// Ежедневная трата на СВО (в рублях) — 35 миллиардов рублей.
// Эта цифра взята из расчёта: бюджет на оборону 12,93 трлн руб. / 365 дней.
$daily_cost_rub = 35000000000;

// Дата начала СВО (в формате ГГГГ-ММ-ДД)
$start_date = '2022-02-24';

// Устанавливаем часовой пояс на московский, чтобы время на сайте было корректным.
// Без этого date() могло бы показать время UTC (Лондон).
date_default_timezone_set('Europe/Moscow');

// -----------------------------------------------------------------------------
// 2. РАСЧЁТ КОЛИЧЕСТВА ДНЕЙ, ПРОШЕДШИХ С НАЧАЛА СВО
// -----------------------------------------------------------------------------

// new DateTime() без аргументов — возвращает объект с текущей датой и временем.
$now = new DateTime();

// new DateTime($start_date) — объект с датой начала.
$start = new DateTime($start_date);

// diff() — метод, который вычисляет разницу между двумя датами.
// Результат — объект DateInterval.
$interval = $now->diff($start);

// Свойство days объекта DateInterval содержит общее количество дней разницы.
$days_passed = $interval->days;

// -----------------------------------------------------------------------------
// 3. РАСЧЁТ ОБЩЕЙ СУММЫ, ПОТРАЧЕННОЙ НА ВОЙНУ
// -----------------------------------------------------------------------------

// Умножаем количество дней на ежедневный расход (арифметика целых чисел).
$total_rub = $days_passed * $daily_cost_rub;

// Формируем строку с текущей датой и временем (например "12.05.2026 14:35:22").
// d = день (01–31), m = месяц (01–12), Y = год (4 цифры).
// H = час (00–23), i = минуты, s = секунды.
$current_datetime = date('d.m.Y H:i:s');

// -----------------------------------------------------------------------------
// 4. ФУНКЦИЯ ФОРМАТИРОВАНИЯ БОЛЬШИХ ЧИСЕЛ (тыс, млн, млрд, трлн, квадр)
// -----------------------------------------------------------------------------
// Эта функция получает число (например 35000000000) и возвращает строку
// "35 млрд". Проверки идут от самого большого диапазона (квадриллион) к маленькому.

/**
 * Форматирует большое число, добавляя единицу измерения (тыс, млн, млрд, трлн, квадр)
 *
 * @param int|float $number Исходное число в рублях
 * @return string Отформатированная строка (например "35 млрд")
 */
function formatWithUnit($number) {
    // 1 квадриллион = 1 000 000 000 000 000 (15 нулей)
    // Если число больше или равно квадриллиону...
    if ($number >= 1000000000000000) {
        // ... делим на квадриллион, округляем до 2 знаков, добавляем "квадр".
        // round() округляет число с плавающей точкой.
        return round($number / 1000000000000000, 2) . ' квадр';
    }
    // 1 триллион = 1 000 000 000 000 (12 нулей)
    elseif ($number >= 1000000000000) {
        return round($number / 1000000000000, 2) . ' трлн';
    }
    // 1 миллиард = 1 000 000 000 (9 нулей)
    elseif ($number >= 1000000000) {
        return round($number / 1000000000, 2) . ' млрд';
    }
    // 1 миллион = 1 000 000 (6 нулей)
    elseif ($number >= 1000000) {
        return round($number / 1000000, 2) . ' млн';
    }
    // 1 тысяча = 1 000 (3 нуля)
    elseif ($number >= 1000) {
        return round($number / 1000, 2) . ' тыс';
    }
    // Если число меньше тысячи — возвращаем как есть (без единицы измерения).
    return (string)$number;
}

// Применяем функцию к ежедневной трате — получаем например "35 млрд".
$daily_formatted = formatWithUnit($daily_cost_rub);

// Применяем к общей сумме — получаем например "52.5 трлн".
$total_formatted = formatWithUnit($total_rub);

// number_format() — встроенная функция, которая расставляет пробелы между разрядами.
// Аргументы: число, сколько знаков после запятой, десятичный разделитель, разделитель тысяч.
// Например: 52500000000000 → "52 500 000 000 000"
$total_raw = number_format($total_rub, 0, '.', ' ');

